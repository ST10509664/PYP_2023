    private void menuSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_menuSaveActionPerformed
        try (FileWriter writer = new FileWriter("report.txt")) {
            writer.write("ESTATE AGENT REPORT");
            writer.write("\n************************");
            writer.write("\nAGENT LOCATION " + location);
            writer.write("\nAGENT NAME: " + name);
            writer.write(String.format("\nPROPERTY PRICE: R %.1f", Double.parseDouble(price)));
            writer.write("\nCOMMISSION PERCENTAGE:" + Double.parseDouble(commission) + "%");
            writer.write(String.format("\nCALUCLATED COMMISSION: R %.1f", calcCommission()));
            writer.write("\n************************");
            txtOutput.append("\nData saved successfully.");
        } catch (IOException e) {
            System.out.println("An error occurred while saving.");
            e.printStackTrace();
        }
    }//GEN-LAST:event_menuSaveActionPerformed

