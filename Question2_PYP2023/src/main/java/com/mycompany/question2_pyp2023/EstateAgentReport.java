    private void menuProcessActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_menuProcessActionPerformed
         name = txtName.getText();
         price = txtPrice.getText();
         commission = txtCommission.getText();
        //get the string name of selected location from cmb
         location = (String) cmbLocation.getSelectedItem();
        
        EstateAgent ea = new EstateAgent();
        Data d = new Data(location, name, price, commission);
        
        if (ea.ValidateData(d)) {
        // if the data is valid
        
        txtOutput.append("AGENT LOCATION: " + location);
        txtOutput.append("\nAGENT NAME: " + name);
        txtOutput.append(String.format("\nPROPERTY PRICE: R %.1f", Double.parseDouble(price)));
        txtOutput.append("\nCOMMISION PERCENTAGE: " + Double.parseDouble(commission) + "%");
        txtOutput.append(String.format("\nCALCULATED COMMISSION: R %.1f", calcCommission()));
       
        } else {
            txtOutput.setText("Please enter valid data.");
        }
        
    }//GEN-LAST:event_menuProcessActionPerformed

